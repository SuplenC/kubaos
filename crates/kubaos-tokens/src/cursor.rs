//! The tokens the pointer is sized by, `crates/kubaos-cursor/src/tokens.rs`: the grid its size
//! keeps to and the scales its bitmaps are drawn at, so the pointer is whole device pixels wherever
//! the rest of the desktop is.
//!
//! # Owns
//!
//! - The module's text.
//!
//! # Not here
//!
//! - Using them: `crates/kubaos-cursor`'s `settings` and `theme`.

use std::fmt::Write as _;
use std::io;
use std::path::Path;

use crate::model::Tokens;
use crate::target::Target;

/// `crates/kubaos-cursor/src/tokens.rs`.
#[derive(Debug)]
pub struct CursorTokens;

impl Target for CursorTokens {
    fn path(&self) -> &'static str {
        "crates/kubaos-cursor/src/tokens.rs"
    }

    fn render(&self, tokens: &Tokens, _root: &Path) -> io::Result<String> {
        let rules = &tokens.rules;
        let scales: Vec<String> = rules.scales.iter().map(|s| format!("{s:?}")).collect();
        let mut out = String::new();
        out.push_str(
            "// @generated by `kubaos-tokens` from `design/tokens.toml`. Change the tokens there and run\n\
             // `cargo run -p kubaos-tokens -- write`; a test fails while this file differs from them.\n\
             \n\
             //! The design tokens the pointer is sized by.\n\
             \n\
             /// Every length is a multiple of this, in logical pixels, so it is whole device pixels at every\n\
             /// one of [`SCALES`].\n",
        );
        let _ = writeln!(out, "pub const GRID: u32 = {};", rules.grid);
        out.push_str("\n/// The display scales every length lands on whole device pixels at.\n");
        let _ = writeln!(
            out,
            "pub const SCALES: [f32; {}] = [{}];",
            scales.len(),
            scales.join(", ")
        );
        Ok(out)
    }
}
