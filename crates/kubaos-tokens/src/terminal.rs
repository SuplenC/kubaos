/// Which palette a colour is read from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Mode {
    /// matugen's `default`: the mode `dot-theme` ran it in.
    Current,
    Dark,
    Light,
}

/// How a colour is spelled.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Form {
    /// `#rrggbb`.
    Hex,
    /// `rrggbb`, as foot and fuzzel take it.
    Bare,
}

/// A colour a slot takes: a role, or one of the terminal's hues, with its lightness moved.
#[derive(Debug, Clone, Copy)]
struct Colour<'a> {
    name: &'a str,
    hue: bool,
    shift: Shift,
}

/// A colour's lightness moved toward or away from the surface, in HSL points.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Shift {
    None,
    /// Away from the surface: a bright ANSI colour.
    Out(u8),
    /// Toward the surface: dim text.
    In(u8),
}

impl Shift {
    /// The points matugen's `lighten` moves the colour by: up for `Out` in dark, down in light.
    fn points(self, dark: bool) -> f32 {
        let (points, out) = match self {
            Shift::None => return 0.0,
            Shift::Out(points) => (points, true),
            Shift::In(points) => (points, false),
        };
        if out == dark {
            f32::from(points)
        } else {
            -f32::from(points)
        }
    }
}

fn role(name: &str) -> Colour<'_> {
    Colour {
        name,
        hue: false,
        shift: Shift::None,
    }
}

fn hue(name: &str) -> Colour<'_> {
    Colour {
        name,
        hue: true,
        shift: Shift::None,
    }
}

impl Colour<'_> {
    fn shifted(self, shift: Shift) -> Self {
        Self { shift, ..self }
    }
}

/// The matugen colour `colour` comes from, or `None` for a role of our own.
fn source<'a>(tokens: &'a Tokens, colour: Colour<'a>) -> Option<&'a str> {
    if colour.hue {
        return Some(colour.name);
    }
    tokens
        .color
        .source
        .get(colour.name)
        .map(String::as_str)
        .filter(|source| !source.is_empty())
}

/// `colour` in a matugen template, read in `mode`: matugen's colour, or ours written out.
fn template(tokens: &Tokens, colour: Colour<'_>, mode: Mode, form: Form) -> String {
    let field = match form {
        Form::Hex => "hex",
        Form::Bare => "hex_stripped",
    };
    let source = source(tokens, colour);
    if let (Mode::Current, Some(source), Shift::None) = (mode, source, colour.shift) {
        return format!("{{{{colors.{source}.default.{field}}}}}");
    }
    let one = |dark: bool| {
        let points = colour.shift.points(dark);
        let palette = if dark { "dark" } else { "light" };
        match source {
            Some(source) if points == 0.0 => format!("{{{{colors.{source}.{palette}.{field}}}}}"),
            Some(source) => format!("{{{{colors.{source}.{palette}.{field} | lighten: {points:.1}}}}}"),
            None => spelled(fallback(tokens, colour, dark), form),
        }
    };
    match mode {
        Mode::Dark => one(true),
        Mode::Light => one(false),
        Mode::Current => {
            let (dark, light) = (one(true), one(false));
            if dark == light {
                dark
            } else {
                format!("<* if {{{{ is_dark_mode }}}} *>{dark}<* else *>{light}<* endif *>")
            }
        }
    }
}

/// `colour` before matugen has run: the role's fallback, or the hue's seed, with its shift.
fn fallback(tokens: &Tokens, colour: Colour<'_>, dark: bool) -> Rgb {
    let rgb = if colour.hue {
        tokens
            .terminal
            .hues
            .ansi()
            .into_iter()
            .find_map(|(name, seed)| (name == colour.name).then_some(seed))
            .expect("a hue is one of [terminal.hues]")
    } else {
        let palette = if dark { &tokens.color.dark } else { &tokens.color.light };
        *palette
            .get(colour.name)
            .expect("every role in [color.source] is in both palettes; the rules refuse one that isn't")
    };
    rgb.lighten(colour.shift.points(dark))
}

fn spelled(rgb: Rgb, form: Form) -> String {
    let hex = format!("{:02x}{:02x}{:02x}", rgb.r, rgb.g, rgb.b);
    match form {
        Form::Hex => format!("#{hex}"),
        Form::Bare => hex,
    }
}

/// The 16 ANSI colours in order: black, the hues and white, then the dim text, the bright hues
/// and the bright white.
fn ansi(tokens: &Tokens) -> [Colour<'_>; 16] {
    let terminal = &tokens.terminal;
    let roles = &terminal.roles;
    let [red, green, yellow, blue, magenta, cyan] = terminal.hues.ansi().map(|(name, _)| hue(name));
    let bright = Shift::Out(terminal.bright);
    [
        role(&roles.black),
        red,
        green,
        yellow,
        blue,
        magenta,
        cyan,
        role(&roles.white),
        role(&roles.white).shifted(Shift::In(terminal.dim)),
        red.shifted(bright),
        green.shifted(bright),
        yellow.shifted(bright),
        blue.shifted(bright),
        magenta.shifted(bright),
        cyan.shifted(bright),
        role(&roles.bright_white),
    ]
}

/// What the TUIs read by name: every colour role, the six hues, and `dim`, ANSI 8's dim text.
fn named(tokens: &Tokens) -> Vec<(&str, Colour<'_>)> {
    let roles = tokens.color.source.keys().map(|name| (name.as_str(), role(name)));
    let hues = tokens
        .terminal
        .hues
        .ansi()
        .into_iter()
        .map(|(name, _)| (name, hue(name)));
    let dim = ansi(tokens)[8];
    roles.chain(hues).chain([("dim", dim)]).collect()
}

/// The type style the terminals set their text in.
fn style(tokens: &Tokens) -> &TypeStyle {
    tokens
        .types
        .get(&tokens.terminal.style)
        .expect("terminal.type names a type style; the rules refuse one that doesn't")
}

/// Logical pixels as the points a terminal sizes fonts and padding in: 72 to the inch, on a
/// screen of 96 logical pixels to the inch.
fn points(px: u16) -> String {
    let points = f32::from(px) * 0.75;
    if points.fract() == 0.0 {
        format!("{points:.0}")
    } else {
        format!("{points}")
    }
}

fn opacity(tokens: &Tokens, name: &str) -> f32 {
    *tokens
        .opacity
        .get(name)
        .expect("the opacity is in [opacity]; the rules refuse one that isn't")
}

/// The file's opening lines, in its comment syntax: that it is generated, then what it is.
fn header(comment: &str, what: &str) -> String {
    let mut text = String::new();
    for line in [
        "@generated by `kubaos-tokens` from `design/tokens.toml`. Change the tokens there and run",
        "`cargo run -p kubaos-tokens -- write`; a test fails while this file differs from them.",
    ] {
        let _ = writeln!(text, "{comment} {line}");
    }
    for line in wrap(what, 98 - comment.len()) {
        let _ = writeln!(text, "{comment} {line}");
    }
    text.push('\n');
    text
}

/// How much Ghostty stretches the font's own line, in percent, so a cell is the style's line.
///
/// # Errors
///
/// When the font can't be read, or isn't a font.
fn cell_stretch(style: &TypeStyle, root: &Path) -> io::Result<u32> {
    let font = fs::read(root.join(MONO_FONT))?;
    let (units, height) = font_line(&font).ok_or_else(|| {
        io::Error::new(
            io::ErrorKind::InvalidData,
            format!("{MONO_FONT} has no head or hhea table"),
        )
    })?;
    let natural = f32::from(style.size) * f32::from(height) / f32::from(units);
    let stretch = (f32::from(style.line) / natural - 1.0) * 100.0;
    #[expect(
        clippy::cast_possible_truncation,
        clippy::cast_sign_loss,
        reason = "A line shorter than its font's is refused by the rules, so the stretch is a small positive percent."
    )]
    let percent = stretch.round().max(0.0) as u32;
    Ok(percent)
}

/// A TrueType font's units per em and its own line (ascender less descender plus line gap), from
/// its `head` and `hhea` tables.
fn font_line(font: &[u8]) -> Option<(u16, u16)> {
    let u16_at = |at: usize| Some(u16::from_be_bytes([*font.get(at)?, *font.get(at + 1)?]));
    let i16_at = |at: usize| u16_at(at).map(|v| i32::from(v.cast_signed()));
    let table = |tag: &[u8; 4]| {
        (0..usize::from(u16_at(4)?)).find_map(|i| {
            let record = 12 + 16 * i;
            if font.get(record..record + 4)? != tag {
                return None;
            }
            let offset = u32::from_be_bytes(font.get(record + 8..record + 12)?.try_into().ok()?);
            usize::try_from(offset).ok()
        })
    };
    let units = u16_at(table(b"head")? + 18)?;
    let hhea = table(b"hhea")?;
    let line = i16_at(hhea + 4)? - i16_at(hhea + 6)? + i16_at(hhea + 8)?;
    Some((units, u16::try_from(line).ok()?))
}

fn ghostty_settings(tokens: &Tokens, root: &Path) -> io::Result<String> {
    let style = style(tokens);
    let terminal = &tokens.terminal;
    let mut out = header(
        "#",
        "Ghostty's type, padding and glass, and the dark fallback palette for before dot-theme has \
         run. config/ghostty/config loads it first, then the wallpaper's palette, then your settings.",
    );
    let _ = writeln!(out, "font-family = \"{}\"", tokens.font.family.name(style.family));
    let _ = writeln!(out, "font-size = {}", points(style.size));
    let _ = writeln!(
        out,
        "# Geist Mono's own line, 1.3 times its size, stretched to the style's {}.",
        style.line
    );
    let _ = writeln!(out, "adjust-cell-height = {}%", cell_stretch(style, root)?);
    let _ = writeln!(out, "window-padding-x = {}", points(terminal.padding_x));
    let _ = writeln!(out, "window-padding-y = {}", points(terminal.padding_y));
    let _ = writeln!(out, "background-opacity = {}", opacity(tokens, &terminal.opacity));
    out.push('\n');
    ghostty_palette(tokens, &mut out, |colour| {
        spelled(fallback(tokens, colour, true), Form::Hex)
    });
    Ok(out)
}

fn ghostty_template(tokens: &Tokens) -> String {
    let mut out = header(
        "#",
        "matugen's template of Ghostty's palette, rendered by dot-theme to \
         ~/.local/state/theme/ghostty, which config/ghostty/config loads after config/ghostty/tokens.",
    );
    ghostty_palette(tokens, &mut out, |colour| {
        template(tokens, colour, Mode::Current, Form::Hex)
    });
    out
}

/// Ghostty's colours, each spelled by `spell`.
fn ghostty_palette<'a>(tokens: &'a Tokens, out: &mut String, spell: impl Fn(Colour<'a>) -> String) {
    let roles = &tokens.terminal.roles;
    for (key, name) in [
        ("background", &roles.background),
        ("foreground", &roles.foreground),
        ("cursor-color", &roles.cursor),
        ("cursor-text", &roles.cursor_text),
        ("selection-background", &roles.selection),
        ("selection-foreground", &roles.selection_text),
        ("split-divider-color", &roles.divider),
    ] {
        let _ = writeln!(out, "{key} = {}", spell(role(name)));
    }
    for (index, colour) in ansi(tokens).into_iter().enumerate() {
        let _ = writeln!(out, "palette = {index}={}", spell(colour));
    }
}

fn foot_settings(tokens: &Tokens) -> String {
    let style = style(tokens);
    let terminal = &tokens.terminal;
    let size = points(style.size);
    let mut out = header(
        ";",
        "foot's type and padding, and the dark fallback palette for before dot-theme has run. \
         config/foot/foot.ini includes it first, then the wallpaper's palette, then your settings.",
    );
    let family = tokens.font.family.name(style.family);
    let _ = writeln!(
        out,
        "font={family}:size={size}, {}:size={size}, monospace:size={size}",
        terminal.glyphs
    );
    let _ = writeln!(out, "line-height={}", points(style.line));
    let _ = writeln!(out, "pad={}x{} center", terminal.padding_x, terminal.padding_y);
    out.push('\n');
    out.push_str("[colors]\n");
    foot_palette(tokens, &mut out, |colour| {
        spelled(fallback(tokens, colour, true), Form::Bare)
    });
    out
}

fn foot_template(tokens: &Tokens) -> String {
    let mut out = header(
        ";",
        "matugen's template of foot's palettes, rendered by dot-theme to \
         ~/.local/state/theme/foot.ini, which config/foot/foot.ini includes. foot can't read its \
         colours again, so both are here: [colors] dark, [colors2] light. A new window opens in \
         the mode dot-theme ran in, and dot-theme signals the open ones (SIGUSR1 dark, SIGUSR2 light).",
    );
    out.push_str("[main]\n");
    out.push_str("initial-color-theme=<* if {{ is_dark_mode }} *>1<* else *>2<* endif *>\n\n");
    out.push_str("[colors]\n");
    foot_palette(tokens, &mut out, |colour| {
        template(tokens, colour, Mode::Dark, Form::Bare)
    });
    out.push_str("\n[colors2]\n");
    foot_palette(tokens, &mut out, |colour| {
        template(tokens, colour, Mode::Light, Form::Bare)
    });
    out
}

/// foot's colours, each spelled by `spell`. Its prompts are a role on its container: a jump
/// label in the accent, a search's match or the scrollback's place as a selected row, no match
/// as an error.
fn foot_palette<'a>(tokens: &'a Tokens, out: &mut String, spell: impl Fn(Colour<'a>) -> String) {
    let roles = &tokens.terminal.roles;
    let _ = writeln!(out, "alpha={}", opacity(tokens, &tokens.terminal.opacity));
    for (key, name) in [
        ("background", &roles.background),
        ("foreground", &roles.foreground),
        ("selection-background", &roles.selection),
        ("selection-foreground", &roles.selection_text),
        ("urls", &roles.url),
    ] {
        let _ = writeln!(out, "{key}={}", spell(role(name)));
    }
    for (key, fg, bg) in [
        ("cursor", roles.cursor_text.as_str(), roles.cursor.as_str()),
        ("jump-labels", "on_primary", "primary"),
        ("scrollback-indicator", &roles.selection_text, &roles.selection),
        ("search-box-match", &roles.selection_text, &roles.selection),
        ("search-box-no-match", "on_error", "error"),
    ] {
        let _ = writeln!(out, "{key}={} {}", spell(role(fg)), spell(role(bg)));
    }
    for (index, colour) in ansi(tokens).into_iter().enumerate() {
        let key = if index < 8 { "regular" } else { "bright" };
        let _ = writeln!(out, "{key}{}={}", index % 8, spell(colour));
    }
}

