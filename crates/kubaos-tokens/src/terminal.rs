/// The monospace family's regular face, whose own line the terminals stretch to the type style's.
/// `kubaos-ui` embeds the release the system installs (`geist-font`).
const MONO_FONT: &str = "crates/kubaos-ui/assets/fonts/GeistMono-Regular.ttf";

/// The lines around the block `kubaos-tokens` writes inside the hand-written
/// `config/matugen/config.toml`.
const HUES_START: &str = "# @generated by `kubaos-tokens` from design/tokens.toml's [terminal.hues]: begin";
const HUES_END: &str = "# @generated: end";

/// The gap between the launcher's field and its list, a step of the spacing scale.
const LIST_GAP: u16 = 8;

/// One generated file: where it lives and how its text is made.
#[derive(Debug)]
pub struct Output {
    path: &'static str,
    render: Render,
}

/// How an output's text is made: from the tokens alone, or reading a file of the repo too.
#[derive(Debug)]
enum Render {
    Tokens(fn(&Tokens) -> String),
    Reading(fn(&Tokens, &Path) -> io::Result<String>),
}

impl Target for Output {
    fn path(&self) -> &'static str {
        self.path
    }

    fn render(&self, tokens: &Tokens, root: &Path) -> io::Result<String> {
        match self.render {
            Render::Tokens(render) => Ok(render(tokens)),
            Render::Reading(render) => render(tokens, root),
        }
    }
}

