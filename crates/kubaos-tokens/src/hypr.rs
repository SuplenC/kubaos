//! The tokens Hyprland draws with, `config/hypr/tokens.lua`: the durations and curves its
//! animations take, the focus glow its active window's shadow is fitted to, the opacities, and how
//! a tube strikes, which the active window's border plays as focus arrives.
//!
//! # Owns
//!
//! - The module's text.
//!
//! # Not here
//!
//! - Using them: `config/hypr/looks.lua` and `config/hypr/focus.lua`.

use std::fmt::Write as _;
use std::io;
use std::path::Path;

use crate::model::Tokens;
use crate::target::Target;

/// `config/hypr/tokens.lua`.
#[derive(Debug)]
pub struct HyprTokens;

impl Target for HyprTokens {
    fn path(&self) -> &'static str {
        "config/hypr/tokens.lua"
    }

    fn render(&self, tokens: &Tokens, _root: &Path) -> io::Result<String> {
        let focus = &tokens.focus;
        let floats = |values: &[f32]| values.iter().map(|v| format!("{v:?}")).collect::<Vec<_>>().join(", ");
        let mut out = String::new();
        out.push_str(
            "-- @generated by `kubaos-tokens` from `design/tokens.toml`. Change the tokens there and run\n\
             -- `cargo run -p kubaos-tokens -- write`; a test fails while this file differs from them.\n\
             --\n\
             -- The design tokens Hyprland draws with, by their names in `design/tokens.toml`.\n\
             \n\
             return {\n\
             \x20 -- Durations in milliseconds.\n\
             \x20 duration = {\n",
        );
        for (name, duration) in &tokens.duration {
            let _ = writeln!(out, "    {name} = {},", duration.ms);
        }
        out.push_str("  },\n  -- Easing curves, as CSS cubic béziers: x1, y1, x2, y2.\n  easing = {\n");
        for (name, easing) in &tokens.easing {
            let _ = writeln!(out, "    {name} = {{ {} }},", floats(&easing.curve));
        }
        out.push_str(
            "  },\n\
             \x20 -- The focus glow: a near one and a far, faint one, each fading from its opacity at the\n\
             \x20 -- tube to nothing at its reach outside it, in logical pixels.\n\
             \x20 focus = {\n",
        );
        let _ = writeln!(out, "    near = {},", focus.near);
        let _ = writeln!(out, "    near_opacity = {:?},", focus.near_opacity);
        let _ = writeln!(out, "    far = {},", focus.far);
        let _ = writeln!(out, "    far_opacity = {:?},", focus.far_opacity);
        out.push_str(
            "  },\n\
             \x20 -- Opacities laid over a colour role.\n\
             \x20 opacity = {\n",
        );
        for (name, opacity) in &tokens.opacity {
            let _ = writeln!(out, "    {name} = {opacity:?},");
        }
        out.push_str(
            "  },\n\
             \x20 neon = {\n\
             \x20   -- A tube striking: its brightness, 0 to 1, through even steps over `duration.medium`.\n",
        );
        let _ = writeln!(out, "    strike = {{ {} }},", floats(&tokens.neon.strike));
        out.push_str("  },\n}\n");
        Ok(out)
    }
}
