use std::path::Path;

use super::Form;
use super::Mode;
use super::OUTPUTS;
use super::Shift;
use super::ansi;
use super::cell_stretch;
use super::hue;
use super::role;
use super::template;
use crate::Target;
use crate::model::Rgb;

fn root() -> &'static Path {
    Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/../.."))
}

fn tokens() -> crate::Tokens {
    crate::load(root()).expect("design/tokens.toml holds every rule")
}

fn output(path: &str) -> String {
    let tokens = tokens();
    let output = OUTPUTS
        .iter()
        .find(|output| output.path() == path)
        .expect("an output at that path");
    output.render(&tokens, root()).expect("render the output")
}

#[test]
fn a_role_with_a_matugen_source_reads_matugens_colour_in_the_mode_dot_theme_ran_in() {
    let tokens = tokens();

    let text = template(&tokens, role("cold"), Mode::Current, Form::Hex);

    assert_eq!(text, "{{colors.tertiary.default.hex}}");
}

#[test]
fn a_role_of_our_own_is_written_out_for_each_mode() {
    let tokens = tokens();

    let text = template(&tokens, role("warning"), Mode::Current, Form::Bare);

    assert_eq!(text, "<* if {{ is_dark_mode }} *>fcc618<* else *>806000<* endif *>");
}

#[test]
fn a_bright_hue_moves_away_from_the_surface_in_both_modes() {
    let tokens = tokens();

    let text = template(&tokens, hue("red").shifted(Shift::Out(6)), Mode::Current, Form::Hex);

    assert_eq!(
        text,
        "<* if {{ is_dark_mode }} *>{{colors.red.dark.hex | lighten: 6.0}}<* else *>\
         {{colors.red.light.hex | lighten: -6.0}}<* endif *>"
    );
}

#[test]
fn ansi_8_is_ansi_7_dimmed_toward_the_surface() {
    let tokens = tokens();
    let colours = ansi(&tokens);

    let dim = template(&tokens, colours[8], Mode::Dark, Form::Hex);

    assert_eq!(dim, "{{colors.on_surface_variant.dark.hex | lighten: -16.0}}");
}

#[test]
fn lightening_matches_matugens_hsl_lighten() {
    let red = Rgb::parse("#ffb4ab").expect("a colour");

    let darker = red.lighten(-6.0);

    assert_eq!(darker, Rgb::parse("#ff998c").expect("a colour"));
}

#[test]
fn the_terminals_cell_is_the_type_styles_line() {
    let tokens = tokens();
    let style = &tokens.types["mono_large"];

    let stretch = cell_stretch(style, root()).expect("read Geist Mono");

    let natural = f32::from(style.size) * 1.3;
    let cell = (natural * (1.0 + f32::from(u16::try_from(stretch).expect("a small percent")) / 100.0)).round();
    assert!(
        (cell - f32::from(style.line)).abs() < f32::EPSILON,
        "a {cell} cell for a {} line",
        style.line
    );
}

#[test]
fn foot_holds_both_palettes_and_opens_in_the_mode_dot_theme_ran_in() {
    let text = output("config/matugen/templates/foot.ini");

    assert!(text.contains("initial-color-theme=<* if {{ is_dark_mode }} *>1<* else *>2<* endif *>"));
    assert!(text.contains("[colors]\nalpha="));
    assert!(text.contains("background={{colors.surface.dark.hex_stripped}}"));
    assert!(text.contains("background={{colors.surface.light.hex_stripped}}"));
}

#[test]
fn the_hues_block_is_the_only_part_of_matugens_config_written() {
    let written = output("config/matugen/config.toml");
    let shipped = std::fs::read_to_string(root().join("config/matugen/config.toml")).expect("read the config");

    let outside = |text: &str| -> Vec<String> {
        let lines: Vec<String> = text.lines().map(String::from).collect();
        let start = lines
            .iter()
            .position(|l| l.starts_with("# @generated by"))
            .expect("the block's start");
        let end = lines
            .iter()
            .position(|l| l == "# @generated: end")
            .expect("the block's end");
        [lines[..start].to_vec(), lines[end..].to_vec()].concat()
    };

    assert_eq!(outside(&written), outside(&shipped));
    assert!(written.contains("[config.custom_colors]\nred = \"#f7768e\"\n"));
}
