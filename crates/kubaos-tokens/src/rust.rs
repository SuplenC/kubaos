//! The Rust module of `kubaos-ui`, `crates/kubaos-ui/src/tokens.rs`: every token as a closed enum
//! or a constant, so a value off the scale can't be written in an iced app.
//!
//! # Owns
//!
//! - The module's text: the enums, their values and docs, the two fallback palettes.
//!
//! # Not here
//!
//! - Turning the tokens into iced values (colours, fonts, pixels at a scale): `kubaos-ui`.

use std::collections::BTreeMap;

use crate::model::Family;
use crate::model::Rgb;
use crate::model::Tokens;
use crate::model::Weight;
use crate::target::Target;

/// `crates/kubaos-ui/src/tokens.rs`.
#[derive(Debug)]
pub struct RustModule;

impl Target for RustModule {
    fn path(&self) -> &'static str {
        "crates/kubaos-ui/src/tokens.rs"
    }

    fn render(&self, tokens: &Tokens) -> String {
        let mut out = Writer::default();
        header(&mut out);
        rules(&mut out, tokens);
        lengths(&mut out, tokens);
        types(&mut out, tokens);
        motion(&mut out, tokens);
        surfaces(&mut out, tokens);
        colors(&mut out, tokens);
        symbols(&mut out, tokens);
        out.text
    }
}

/// The module's text, built line by line.
#[derive(Default)]
struct Writer {
    text: String,
}

impl Writer {
    fn line(&mut self, line: impl AsRef<str>) {
        self.text.push_str(line.as_ref());
        self.text.push('\n');
    }

    fn blank(&mut self) {
        self.text.push('\n');
    }

    fn doc(&mut self, indent: &str, doc: &str) {
        for line in wrap(doc, 100 - indent.len() - 4) {
            self.line(format!("{indent}/// {line}"));
        }
    }
}

/// `text` in lines of at most `width` characters, broken at spaces.
fn wrap(text: &str, width: usize) -> Vec<String> {
    let mut lines: Vec<String> = Vec::new();
    for word in text.split_whitespace() {
        match lines.last_mut() {
            Some(line) if line.chars().count() + 1 + word.chars().count() <= width => {
                line.push(' ');
                line.push_str(word);
            }
            _ => lines.push(word.to_string()),
        }
    }
    lines
}

/// `body_large` as `BodyLarge`.
fn camel(name: &str) -> String {
    name.split('_')
        .map(|word| {
            let mut chars = word.chars();
            chars
                .next()
                .map(|first| first.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn header(out: &mut Writer) {
    out.line("// @generated by `kubaos-tokens` from `design/tokens.toml`. Change the tokens there and run");
    out.line("// `cargo run -p kubaos-tokens -- write`; a test fails while this file differs from them.");
    out.blank();
    out.line("//! The design tokens: every length, type style, duration, curve and colour role, as closed");
    out.line("//! enums and constants. A length is a variant, never a number, so nothing off the scale can be");
    out.line("//! written.");
    out.line("//!");
    out.line("//! # Owns");
    out.line("//!");
    out.line("//! - The values, generated from `design/tokens.toml`.");
    out.line("//!");
    out.line("//! # Not here");
    out.line("//!");
    out.line("//! - Turning them into iced values at a display scale: the rest of `kubaos-ui`.");
}

fn rules(out: &mut Writer, tokens: &Tokens) {
    let rules = &tokens.rules;
    out.blank();
    out.line("/// Every spacing, size, radius, icon size, line height and shadow is a multiple of this, in");
    out.line("/// logical pixels.");
    out.line(format!("pub const GRID: u16 = {};", rules.grid));
    out.blank();
    out.line("/// The only font sizes, in logical pixels.");
    out.line(format!(
        "pub const FONT_SIZES: [u16; {}] = [{}];",
        rules.font_sizes.len(),
        join(&rules.font_sizes)
    ));
    out.blank();
    out.line("/// The display scales every length lands on whole device pixels at.");
    out.line(format!(
        "pub const SCALES: [f32; {}] = [{}];",
        rules.scales.len(),
        rules
            .scales
            .iter()
            .map(|s| format!("{s:?}"))
            .collect::<Vec<_>>()
            .join(", ")
    ));
    out.blank();
    out.line("/// A hairline's width in device pixels, at every scale.");
    out.line(format!(
        "pub const HAIRLINE_DEVICE_PX: u16 = {};",
        tokens.stroke.hairline_device_px
    ));
    out.blank();
    out.line("/// The focus ring's, the spinner's and the check mark's stroke in logical pixels, drawn rounded");
    out.line("/// half up to whole device pixels.");
    out.line(format!("pub const STROKE_THIN: u16 = {};", tokens.stroke.thin));
    out.blank();
    out.line("/// A symbol's stroke on its 24 unit grid; drawn scaled to the symbol's size, then rounded half up to");
    out.line("/// whole device pixels.");
    out.line(format!("pub const SYMBOL_STROKE: u16 = {};", tokens.stroke.symbol));
    out.blank();
    out.line("/// How far the focus ring's outer edge stands outside its control, in logical pixels.");
    out.line(format!("pub const FOCUS_OFFSET: u16 = {};", tokens.focus.offset));
}

fn join(values: &[u16]) -> String {
    values.iter().map(u16::to_string).collect::<Vec<_>>().join(", ")
}

/// A closed enum with one `const fn` reading each variant's value.
struct Scale<'a> {
    doc: &'a str,
    name: &'a str,
    /// Variant name, its doc, its value as Rust.
    variants: Vec<(String, Option<String>, String)>,
    getter_doc: &'a str,
    getter: &'a str,
    ty: &'a str,
}

fn scale(out: &mut Writer, scale: &Scale<'_>) {
    out.blank();
    out.doc("", scale.doc);
    out.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
    out.line(format!("pub enum {} {{", scale.name));
    for (variant, doc, _) in &scale.variants {
        if let Some(doc) = doc {
            out.doc("    ", doc);
        }
        out.line(format!("    {variant},"));
    }
    out.line("}");
    out.blank();
    out.line(format!("impl {} {{", scale.name));
    out.line(format!("    /// Every {}.", camel_words(scale.name)));
    out.line(format!(
        "    pub const ALL: [{}; {}] = [",
        scale.name,
        scale.variants.len()
    ));
    for (variant, _, _) in &scale.variants {
        out.line(format!("        {}::{variant},", scale.name));
    }
    out.line("    ];");
    out.blank();
    out.doc("    ", scale.getter_doc);
    out.line(format!("    pub const fn {}(self) -> {} {{", scale.getter, scale.ty));
    out.line("        match self {");
    for (variant, _, value) in &scale.variants {
        out.line(format!("            {}::{variant} => {value},", scale.name));
    }
    out.line("        }");
    out.line("    }");
    out.line("}");
}

/// `IconSize` as `icon size`, for docs.
fn camel_words(name: &str) -> String {
    let mut words = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() && i > 0 {
            words.push(' ');
        }
        words.push(c.to_ascii_lowercase());
    }
    words
}

fn lengths(out: &mut Writer, tokens: &Tokens) {
    scale(
        out,
        &Scale {
            doc: "A step of the spacing scale: gaps, paddings and insets.",
            name: "Space",
            variants: tokens
                .space
                .values
                .iter()
                .map(|v| (format!("S{v}"), None, v.to_string()))
                .collect(),
            getter_doc: "The step in logical pixels.",
            getter: "px",
            ty: "u16",
        },
    );
    let mut radii: Vec<(String, Option<String>, String)> = tokens
        .radius
        .values
        .iter()
        .map(|v| (format!("R{v}"), None, format!("Some({v})")))
        .collect();
    if tokens.radius.full {
        radii.push((
            "Full".into(),
            Some("Half the shape's shorter side: a pill, or a circle.".into()),
            "None".into(),
        ));
    }
    scale(
        out,
        &Scale {
            doc: "A corner radius.",
            name: "Radius",
            variants: radii,
            getter_doc: "The radius in logical pixels, or `None` for [`Radius::Full`], which depends on the shape.",
            getter: "px",
            ty: "Option<u16>",
        },
    );
    scale(
        out,
        &Scale {
            doc: "An icon's size: the glyph's em box, which its ink sits inside with the font's own margin.",
            name: "IconSize",
            variants: tokens
                .icon
                .sizes
                .iter()
                .map(|v| (format!("S{v}"), None, v.to_string()))
                .collect(),
            getter_doc: "The size in logical pixels.",
            getter: "px",
            ty: "u16",
        },
    );
    scale(
        out,
        &Scale {
            doc: "A fixed dimension of a component.",
            name: "Size",
            variants: tokens
                .size
                .iter()
                .map(|(name, value)| (camel(name), None, value.to_string()))
                .collect(),
            getter_doc: "The dimension in logical pixels.",
            getter: "px",
            ty: "u16",
        },
    );
}

fn types(out: &mut Writer, tokens: &Tokens) {
    let families = &tokens.font.family;
    scale(
        out,
        &Scale {
            doc: "A type family, by the role it plays.",
            name: "Family",
            variants: Family::ALL
                .iter()
                .map(|&family| {
                    (
                        family_variant(family).into(),
                        None,
                        format!("{:?}", families.name(family)),
                    )
                })
                .collect(),
            getter_doc: "The family's name, as its font files spell it.",
            getter: "name",
            ty: "&'static str",
        },
    );
    scale(
        out,
        &Scale {
            doc: "A font weight.",
            name: "Weight",
            variants: Weight::ALL
                .iter()
                .map(|&weight| {
                    let (variant, value) = match weight {
                        Weight::Regular => ("Regular", 400),
                        Weight::Medium => ("Medium", 500),
                        Weight::Semibold => ("Semibold", 600),
                    };
                    (variant.into(), None, value.to_string())
                })
                .collect(),
            getter_doc: "The weight on CSS's 100 to 900 scale.",
            getter: "value",
            ty: "u16",
        },
    );

    // Largest first, so the enum reads like the type scale.
    let mut styles: Vec<_> = tokens.types.iter().collect();
    styles.sort_by_key(|(name, style)| (std::cmp::Reverse(style.size), std::cmp::Reverse(style.line), *name));
    let variant = |name: &String| camel(name);
    out.blank();
    out.line("/// A type style: what a piece of text is drawn with.");
    out.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
    out.line("pub enum Type {");
    for (name, style) in &styles {
        out.doc("    ", &style.purpose);
        out.line(format!("    {},", variant(name)));
    }
    out.line("}");
    out.blank();
    out.line("impl Type {");
    out.line("    /// Every type style, largest first.");
    out.line(format!("    pub const ALL: [Type; {}] = [", styles.len()));
    for (name, _) in &styles {
        out.line(format!("        Type::{},", variant(name)));
    }
    out.line("    ];");
    let getters: [(&str, &str, &str); 4] = [
        ("The font size in logical pixels.", "size", "u16"),
        ("The line height in logical pixels.", "line", "u16"),
        ("The weight.", "weight", "Weight"),
        ("The family.", "family", "Family"),
    ];
    for (doc, getter, ty) in getters {
        out.blank();
        out.line(format!("    /// {doc}"));
        out.line(format!("    pub const fn {getter}(self) -> {ty} {{"));
        out.line("        match self {");
        for (name, style) in &styles {
            let value = match getter {
                "size" => style.size.to_string(),
                "line" => style.line.to_string(),
                "weight" => format!("Weight::{}", weight_variant(style.weight)),
                _ => format!("Family::{}", family_variant(style.family)),
            };
            out.line(format!("            Type::{} => {value},", variant(name)));
        }
        out.line("        }");
        out.line("    }");
    }
    out.line("}");
}

fn family_variant(family: Family) -> &'static str {
    match family {
        Family::Sans => "Sans",
        Family::Mono => "Mono",
        Family::Jp => "Jp",
    }
}

fn weight_variant(weight: Weight) -> &'static str {
    match weight {
        Weight::Regular => "Regular",
        Weight::Medium => "Medium",
        Weight::Semibold => "Semibold",
    }
}

fn motion(out: &mut Writer, tokens: &Tokens) {
    let mut durations: Vec<_> = tokens.duration.iter().collect();
    durations.sort_by_key(|(name, duration)| (duration.ms, *name));
    scale(
        out,
        &Scale {
            doc: "How long an animation runs. Each picks the duration for what it is, never by feel; the \
                  speed setting scales them all.",
            name: "Duration",
            variants: durations
                .into_iter()
                .map(|(name, d)| (camel(name), Some(d.purpose.clone()), d.ms.to_string()))
                .collect(),
            getter_doc: "The duration in milliseconds, at speed 1.",
            getter: "ms",
            ty: "u32",
        },
    );
    scale(
        out,
        &Scale {
            doc: "An easing curve.",
            name: "Easing",
            variants: tokens
                .easing
                .iter()
                .map(|(name, e)| {
                    let [x1, y1, x2, y2] = e.curve;
                    (
                        camel(name),
                        Some(e.purpose.clone()),
                        format!("[{x1:?}, {y1:?}, {x2:?}, {y2:?}]"),
                    )
                })
                .collect(),
            getter_doc: "The curve as a CSS cubic bézier: x1, y1, x2, y2.",
            getter: "curve",
            ty: "[f32; 4]",
        },
    );
}

fn surfaces(out: &mut Writer, tokens: &Tokens) {
    scale(
        out,
        &Scale {
            doc: "An opacity laid over a colour role.",
            name: "Opacity",
            variants: tokens
                .opacity
                .iter()
                .map(|(name, value)| (camel(name), None, format!("{value:?}")))
                .collect(),
            getter_doc: "The opacity, 0 to 1.",
            getter: "value",
            ty: "f32",
        },
    );
    out.blank();
    out.line("/// A shadow: offset down and blur in logical pixels, and its opacity.");
    out.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
    out.line("pub enum Shadow {");
    for name in tokens.shadow.keys() {
        out.line(format!("    {},", camel(name)));
    }
    out.line("}");
    out.blank();
    out.line("impl Shadow {");
    let getters: [(&str, &str, &str); 3] = [
        ("How far down the shadow falls, in logical pixels.", "y", "u16"),
        ("The blur radius in logical pixels.", "blur", "u16"),
        ("The opacity, 0 to 1.", "opacity", "f32"),
    ];
    for (i, (doc, getter, ty)) in getters.into_iter().enumerate() {
        if i > 0 {
            out.blank();
        }
        out.line(format!("    /// {doc}"));
        out.line(format!("    pub const fn {getter}(self) -> {ty} {{"));
        out.line("        match self {");
        for (name, shadow) in &tokens.shadow {
            let value = match getter {
                "y" => shadow.y.to_string(),
                "blur" => shadow.blur.to_string(),
                _ => format!("{:?}", shadow.opacity),
            };
            out.line(format!("            Shadow::{} => {value},", camel(name)));
        }
        out.line("        }");
        out.line("    }");
    }
    out.line("}");
}

fn colors(out: &mut Writer, tokens: &Tokens) {
    let colors = &tokens.color;
    out.blank();
    out.line("/// An opaque colour.");
    out.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
    out.line("pub struct Rgb {");
    out.line("    pub r: u8,");
    out.line("    pub g: u8,");
    out.line("    pub b: u8,");
    out.line("}");
    out.blank();
    out.line("/// Light or dark.");
    out.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
    out.line("pub enum Mode {");
    out.line("    Light,");
    out.line("    Dark,");
    out.line("}");
    out.blank();
    out.line("/// Every colour role. At runtime matugen derives them from the wallpaper; [`DARK`] and [`LIGHT`]");
    out.line("/// are the fallback, from the default wallpaper.");
    out.line("#[derive(Debug, Clone, Copy, PartialEq)]");
    out.line("pub struct Palette<C = Rgb> {");
    for (role, source) in &colors.source {
        if source.is_empty() {
            out.line("    /// Ours: the same whatever the wallpaper.");
        } else {
            out.line(format!("    /// matugen's `{source}`."));
        }
        out.line(format!("    pub {role}: C,"));
    }
    out.line("}");
    out.blank();
    out.line("impl<C: Copy> Palette<C> {");
    out.line("    /// The same roles, each colour passed through `f`.");
    out.line("    pub fn map<D>(self, f: impl Fn(C) -> D) -> Palette<D> {");
    out.line("        Palette {");
    for role in colors.source.keys() {
        out.line(format!("            {role}: f(self.{role}),"));
    }
    out.line("        }");
    out.line("    }");
    out.line("}");
    palette(out, "DARK", "The dark fallback palette.", &colors.dark);
    palette(out, "LIGHT", "The light fallback palette.", &colors.light);
    out.blank();
    out.line("/// The fallback palette of `mode`.");
    out.line("pub const fn palette(mode: Mode) -> Palette {");
    out.line("    match mode {");
    out.line("        Mode::Light => LIGHT,");
    out.line("        Mode::Dark => DARK,");
    out.line("    }");
    out.line("}");
}

fn palette(out: &mut Writer, name: &str, doc: &str, roles: &BTreeMap<String, Rgb>) {
    out.blank();
    out.line(format!("/// {doc}"));
    out.line(format!("pub const {name}: Palette = Palette {{"));
    for (role, rgb) in roles {
        out.line(format!(
            "    {role}: Rgb {{ r: 0x{:02x}, g: 0x{:02x}, b: 0x{:02x} }},",
            rgb.r, rgb.g, rgb.b
        ));
    }
    out.line("};");
}

fn symbols(out: &mut Writer, tokens: &Tokens) {
    out.blank();
    out.line("/// A symbol of KubaOS Symbols, by the Material Symbols name it replaces. Its drawing is an SVG on a");
    out.line("/// 24 unit grid with a 2 unit stroke, in `assets/symbols/`.");
    out.line("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
    out.line("pub enum Icon {");
    for (name, symbol) in &tokens.symbols {
        match (&symbol.tabler, &symbol.drawn) {
            (Some(tabler), _) => out.line(format!("    /// Tabler's `{tabler}`.")),
            (None, Some(drawn)) => out.doc("    ", &format!("Ours: {drawn}.")),
            (None, None) => {}
        }
        out.line(format!("    {},", camel(name)));
    }
    out.line("}");
    out.blank();
    out.line("impl Icon {");
    out.line("    /// Every symbol.");
    out.line(format!("    pub const ALL: [Icon; {}] = [", tokens.symbols.len()));
    for name in tokens.symbols.keys() {
        out.line(format!("        Icon::{},", camel(name)));
    }
    out.line("    ];");
    out.blank();
    out.line("    /// The symbol's name, the Material Symbols name it replaces.");
    out.line("    pub const fn name(self) -> &'static str {");
    out.line("        match self {");
    for name in tokens.symbols.keys() {
        out.line(format!("            Icon::{} => {name:?},", camel(name)));
    }
    out.line("        }");
    out.line("    }");
    out.blank();
    out.line("    /// The Tabler icon it is, or `None` for one of ours.");
    out.line("    pub const fn tabler(self) -> Option<&'static str> {");
    out.line("        match self {");
    for (name, symbol) in &tokens.symbols {
        let value = symbol
            .tabler
            .as_ref()
            .map_or_else(|| "None".to_string(), |t| format!("Some({t:?})"));
        out.line(format!("            Icon::{} => {value},", camel(name)));
    }
    out.line("        }");
    out.line("    }");
    out.blank();
    out.line("    /// The drawing, an SVG whose stroke width is `SYMBOL_STROKE`.");
    out.line("    pub const fn svg(self) -> &'static str {");
    out.line("        match self {");
    for name in tokens.symbols.keys() {
        out.line(format!(
            "            Icon::{} => include_str!(\"../assets/symbols/{name}.svg\"),",
            camel(name)
        ));
    }
    out.line("        }");
    out.line("    }");
    out.line("}");
}

