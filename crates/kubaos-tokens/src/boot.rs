//! The boot screens' copies of the tokens. Plymouth and GRUB run before the root file system is
//! there to read `design/tokens.toml` from, draw in device pixels and only ever in the dark
//! palette, so the values they need are written into their own files:
//!
//! - [`PlymouthScript`]: the block of `kubaos.script` between its token markers, holding every
//!   `tokens.…` value the rest of the script reads, and nothing else.
//! - [`PlymouthTheme`]: the theme's `kubaos.plymouth`, for the console's colours.
//! - [`GrubTheme`]: GRUB's `theme.txt`, written from `theme.txt.in` with each `{{…}}` worked out at
//!   GRUB's scale.
//!
//! # Owns
//!
//! - Which tokens each boot screen can name, how they are spelled there, and the arithmetic GRUB's
//!   template may do.
//!
//! # Not here
//!
//! - The pictures both draw (the field, the keycaps, the menu's boxes): `branding/boot.py`, which
//!   reads the tokens itself. Installing them, and the GRUB fonts `theme.txt` names:
//!   `install_boot_theme` in `system/lib.sh`.

use std::collections::BTreeSet;
use std::fs;
use std::io;
use std::path::Path;

use crate::model::Family;
use crate::model::Rgb;
use crate::model::Tokens;
use crate::model::Weight;
use crate::target::Target;

/// The Plymouth theme's script.
const SCRIPT: &str = "system/files/plymouth/kubaos/kubaos.script";
/// The line before the generated block, and the line after it.
const BEGIN: &str = "# --- tokens: @generated by `kubaos-tokens` from `design/tokens.toml` ----------";
const END: &str = "# --- end of tokens ------------------------------------------------------------";

/// GRUB's theme, its template, and the directory of the pictures the template measures.
const GRUB_THEME: &str = "system/files/grub/kubaos/theme.txt";
const GRUB_TEMPLATE: &str = "system/files/grub/theme.txt.in";
const GRUB_PICTURES: &str = "system/files/grub/kubaos";

/// The block of `kubaos.script` between [`BEGIN`] and [`END`].
#[derive(Debug)]
pub struct PlymouthScript;

/// `system/files/plymouth/kubaos/kubaos.plymouth`, the theme's file, for its console colours.
#[derive(Debug)]
pub struct PlymouthTheme;

/// `system/files/grub/kubaos/theme.txt`.
#[derive(Debug)]
pub struct GrubTheme;

impl Target for PlymouthScript {
    fn path(&self) -> &'static str {
        SCRIPT
    }

    fn render(&self, tokens: &Tokens, root: &Path) -> io::Result<String> {
        let script = fs::read_to_string(root.join(SCRIPT))?;
        let (head, rest) = script
            .split_once(&format!("{BEGIN}\n"))
            .ok_or_else(|| invalid(format!("{SCRIPT} has no line `{BEGIN}`")))?;
        let (_, tail) = rest
            .split_once(&format!("{END}\n"))
            .ok_or_else(|| invalid(format!("{SCRIPT} has no line `{END}` after its tokens")))?;
        let mut names = BTreeSet::new();
        for line in head.lines().chain(tail.lines()) {
            references(code(line), &mut names);
        }
        let mut out = format!("{head}{BEGIN}\n");
        out.push_str("# Every `tokens.` value this script reads: colours from the dark palette, as red, green\n");
        out.push_str("# and blue from 0 to 1; lengths in logical pixels; durations in milliseconds. Change them\n");
        out.push_str("# in design/tokens.toml and run `cargo run -p kubaos-tokens -- write`.\n");
        for name in &names {
            for line in plymouth_value(tokens, name)? {
                out.push_str(&line);
                out.push('\n');
            }
        }
        out.push_str(END);
        out.push('\n');
        out.push_str(tail);
        Ok(out)
    }
}

impl Target for PlymouthTheme {
    fn path(&self) -> &'static str {
        "system/files/plymouth/kubaos/kubaos.plymouth"
    }

    fn render(&self, tokens: &Tokens, _root: &Path) -> io::Result<String> {
        let hex = |role: &str| {
            let Rgb { r, g, b } = *tokens
                .color
                .dark
                .get(role)
                .ok_or_else(|| invalid(format!("the dark palette has no {role}")))?;
            Ok::<_, io::Error>(format!("0x{r:02x}{g:02x}{b:02x}"))
        };
        Ok(format!(
            "# @generated by `kubaos-tokens` from `design/tokens.toml`. Change the tokens there and run\n\
             # `cargo run -p kubaos-tokens -- write`.\n\
             [Plymouth Theme]\n\
             Name=KubaOS\n\
             Description=The KubaOS neon sign switching on in the dark, with the disk passphrase prompt\n\
             ModuleName=script\n\
             \n\
             [script]\n\
             ImageDir=/usr/share/plymouth/themes/kubaos\n\
             ScriptFile=/usr/share/plymouth/themes/kubaos/kubaos.script\n\
             # Console text (Esc, or a boot that falls back to details): a note on the splash's dark.\n\
             ConsoleLogTextColor={}\n\
             ConsoleLogBackgroundColor={}\n",
            hex("on_surface_variant")?,
            hex("surface_container_lowest")?,
        ))
    }
}

impl Target for GrubTheme {
    fn path(&self) -> &'static str {
        GRUB_THEME
    }

    fn render(&self, tokens: &Tokens, root: &Path) -> io::Result<String> {
        let template = fs::read_to_string(root.join(GRUB_TEMPLATE))?;
        let mut out = String::new();
        out.push_str("# @generated by `kubaos-tokens` from system/files/grub/theme.txt.in and\n");
        out.push_str("# design/tokens.toml. Change those and run `cargo run -p kubaos-tokens -- write`.\n");
        let mut rest = template.as_str();
        while let Some((before, after)) = rest.split_once("{{") {
            let (expr, after) = after
                .split_once("}}")
                .ok_or_else(|| invalid(format!("{GRUB_TEMPLATE}: a `{{{{` with no `}}}}` after it")))?;
            out.push_str(before);
            out.push_str(&grub_value(tokens, root, expr.trim())?);
            rest = after;
        }
        out.push_str(rest);
        Ok(out)
    }
}

fn invalid(message: String) -> io::Error {
    io::Error::new(io::ErrorKind::InvalidData, message)
}

/// `line` without its comment. The script's strings hold no `#`.
fn code(line: &str) -> &str {
    line.split_once('#').map_or(line, |(code, _)| code)
}

/// Adds every `tokens.a.b` or `tokens.a.b.c` in `code` to `names`, as `a.b` or `a.b.c`.
fn references(code: &str, names: &mut BTreeSet<String>) {
    let word = |c: char| c.is_ascii_alphanumeric() || c == '_';
    let mut from = 0;
    while let Some(at) = code[from..].find("tokens.") {
        let start = from + at;
        from = start + "tokens.".len();
        if code[..start].chars().next_back().is_some_and(|c| word(c) || c == '.') {
            continue;
        }
        let path: String = code[from..].chars().take_while(|&c| word(c) || c == '.').collect();
        let path = path.trim_end_matches('.');
        if !path.is_empty() {
            names.insert(path.to_string());
        }
    }
}

/// The script's lines setting `tokens.<name>`, or an error naming what the tokens lack.
fn plymouth_value(tokens: &Tokens, name: &str) -> io::Result<Vec<String>> {
    let missing = || invalid(format!("{SCRIPT} reads tokens.{name}, which design/tokens.toml lacks"));
    let parts: Vec<&str> = name.split('.').collect();
    let set = |value: String| Ok(vec![format!("tokens.{name} = {value};")]);
    match parts.as_slice() {
        ["color", role] | ["color", role, "r" | "g" | "b"] => {
            let rgb = tokens.color.dark.get(*role).ok_or_else(missing)?;
            let channel = |c: u8| format!("{:.4}", f32::from(c) / 255.0);
            Ok([("r", rgb.r), ("g", rgb.g), ("b", rgb.b)]
                .iter()
                .map(|(field, c)| format!("tokens.color.{role}.{field} = {};", channel(*c)))
                .collect())
        }
        ["easing", curve] => {
            let easing = tokens.easing.get(*curve).ok_or_else(missing)?;
            Ok(easing
                .curve
                .iter()
                .enumerate()
                .map(|(i, v)| format!("tokens.easing.{curve}[{i}] = {v:?};"))
                .collect())
        }
        ["neon", "strike"] => Ok(tokens
            .neon
            .strike
            .iter()
            .enumerate()
            .map(|(i, v)| format!("tokens.neon.strike[{i}] = {v:?};"))
            .collect()),
        ["neon", "strike", "count"] => set(tokens.neon.strike.len().to_string()),
        ["duration", duration] => set(tokens.duration.get(*duration).ok_or_else(missing)?.ms.to_string()),
        ["opacity", opacity] => set(format!("{:?}", tokens.opacity.get(*opacity).ok_or_else(missing)?)),
        ["boot", "plymouth_2x_from"] => set(tokens.boot.plymouth_2x_from.to_string()),
        _ => set(length(tokens, &parts).ok_or_else(missing)?.to_string()),
    }
}

/// A length token in logical pixels, by its path: `space.s8`, `size.control_md`,
/// `radius.control`, `focus.offset`, `stroke.thin`, `icon.s20`, `type.body.line`.
fn length(tokens: &Tokens, parts: &[&str]) -> Option<u16> {
    let step = |name: &str, steps: &[u16]| {
        let value = name.strip_prefix('s')?.parse().ok()?;
        steps.contains(&value).then_some(value)
    };
    match parts {
        ["space", name] => step(name, &tokens.space.values),
        ["icon", name] => step(name, &tokens.icon.sizes),
        ["size", name] => tokens.size.get(*name).copied(),
        ["radius", "small"] => Some(tokens.radius.small),
        ["radius", "control"] => Some(tokens.radius.control),
        ["radius", "surface"] => Some(tokens.radius.surface),
        ["focus", "offset"] => Some(tokens.focus.offset),
        ["stroke", "thin"] => Some(tokens.stroke.thin),
        ["type", style, field] => {
            let style = tokens.types.get(*style)?;
            match *field {
                "size" => Some(style.size),
                "line" => Some(style.line),
                "icon" => Some(style.icon),
                _ => None,
            }
        }
        _ => None,
    }
}

/// One `{{…}}` of GRUB's template: `color.ROLE` as `#rrggbb`, `font.STYLE` as the name of the
/// font `system/25-boot.sh` renders for it, or a sum of lengths in device pixels at GRUB's scale.
fn grub_value(tokens: &Tokens, root: &Path, expr: &str) -> io::Result<String> {
    let unknown = || invalid(format!("{GRUB_TEMPLATE}: `{{{{{expr}}}}}` names nothing in the tokens"));
    if let Some(role) = expr.strip_prefix("color.") {
        let Rgb { r, g, b } = *tokens.color.dark.get(role).ok_or_else(unknown)?;
        return Ok(format!("#{r:02x}{g:02x}{b:02x}"));
    }
    if let Some(style) = expr.strip_prefix("font.") {
        let style = tokens.types.get(style).ok_or_else(unknown)?;
        let family = grub_family(tokens, style.family, style.weight);
        let size = at_grub_scale(tokens, style.size).ok_or_else(|| {
            invalid(format!(
                "{GRUB_TEMPLATE}: `{{{{{expr}}}}}` is a fraction of a pixel at GRUB's scale, which a .pf2 font can't be"
            ))
        })?;
        return Ok(format!("{family} Regular {size}"));
    }
    let mut total = 0_i64;
    let mut sign = 1;
    for (i, word) in expr.split_whitespace().enumerate() {
        if i % 2 == 1 {
            sign = match word {
                "+" => 1,
                "-" => -1,
                _ => return Err(unknown()),
            };
            continue;
        }
        total += sign * grub_term(tokens, root, word)?.ok_or_else(unknown)?;
    }
    Ok(total.to_string())
}

/// One term of a sum in GRUB's template, in device pixels: a whole number, a picture's
/// `png.NAME.width` or `.height`, or a length token at GRUB's scale, then any number of `*N` and
/// `/N`, left to right. A division rounds down, as centring puts an odd spare pixel after. `None`
/// when it names nothing.
fn grub_term(tokens: &Tokens, root: &Path, word: &str) -> io::Result<Option<i64>> {
    let at = word.find(['*', '/']).unwrap_or(word.len());
    let (base, mut ops) = word.split_at(at);
    let Some(mut value) = grub_base(tokens, root, base)? else {
        return Ok(None);
    };
    while let Some(op) = ops.chars().next() {
        let rest = &ops[1..];
        let end = rest.find(['*', '/']).unwrap_or(rest.len());
        let Ok(n) = rest[..end].parse::<i64>() else {
            return Ok(None);
        };
        value = match op {
            '*' => value * n,
            _ if n == 0 => return Ok(None),
            _ => value.div_euclid(n),
        };
        ops = &rest[end..];
    }
    Ok(Some(value))
}

/// A term's value before it is multiplied or divided.
fn grub_base(tokens: &Tokens, root: &Path, word: &str) -> io::Result<Option<i64>> {
    Ok(if let Ok(number) = word.parse::<i64>() {
        Some(number)
    } else if let Some(picture) = word.strip_prefix("png.") {
        let Some((name, side)) = picture.rsplit_once('.') else {
            return Ok(None);
        };
        let (width, height) = png_size(&root.join(GRUB_PICTURES).join(format!("{name}.png")))?;
        match side {
            "width" => Some(i64::from(width)),
            "height" => Some(i64::from(height)),
            _ => None,
        }
    } else {
        let parts: Vec<&str> = word.split('.').collect();
        length(tokens, &parts).and_then(|px| at_grub_scale(tokens, px))
    })
}

/// `logical` pixels in device pixels at GRUB's scale, or `None` when that isn't whole: a length
/// on the grid always is, a font size may not be.
fn at_grub_scale(tokens: &Tokens, logical: u16) -> Option<i64> {
    let device = f32::from(logical) * tokens.boot.grub_scale;
    #[expect(
        clippy::cast_possible_truncation,
        reason = "A whole number of pixels on a screen is far inside i64."
    )]
    let whole = device.round() as i64;
    ((device - device.round()).abs() < 1e-4).then_some(whole)
}

/// The family name `system/25-boot.sh` gives a style's font with `grub-mkfont -n`: the family,
/// then its weight unless it is regular.
fn grub_family(tokens: &Tokens, family: Family, weight: Weight) -> String {
    let name = tokens.font.family.name(family);
    match weight {
        Weight::Regular => name.to_string(),
        Weight::Light => format!("{name} Light"),
        Weight::Medium => format!("{name} Medium"),
        Weight::Semibold => format!("{name} SemiBold"),
    }
}

/// A PNG's width and height, from its header.
fn png_size(path: &Path) -> io::Result<(u32, u32)> {
    const SIGNATURE: &[u8] = b"\x89PNG\r\n\x1a\n";
    let bytes = fs::read(path)?;
    let not_png = || invalid(format!("{} isn't a PNG", path.display()));
    if !bytes.starts_with(SIGNATURE) || bytes.get(12..16) != Some(b"IHDR") {
        return Err(not_png());
    }
    let word = |at: usize| -> io::Result<u32> {
        let four = bytes.get(at..at + 4).ok_or_else(not_png)?;
        Ok(u32::from_be_bytes([four[0], four[1], four[2], four[3]]))
    };
    Ok((word(16)?, word(20)?))
}

