"""Cuts the icon comparison sheet's fonts: the 40 glyphs of glyphs.tsv from each
of the four icon sets, each under a family name of its own, plus icons.tsv,
their codepoints. Run by make-icons.sh, which fetches the pinned sources and
provides fontTools.

    python3 icons.py GLYPHS OUT MATERIAL_TTF MATERIAL_CODEPOINTS \
        PHOSPHOR_TTF PHOSPHOR_CSS LUCIDE_TTF LUCIDE_CSS TABLER_TTF TABLER_CSS
"""
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

glyphs_path, out, *sources = sys.argv[1:]
material_ttf, material_codepoints, *css_sets = sources


def css_codepoints(path, prefix):
    """`.prefix-name:before { content: "\\e123"; }` rules, as name -> codepoint."""
    rule = re.compile(r"\." + prefix + r"([a-z0-9-]+):+before\s*\{\s*content:\s*\"\\([0-9a-fA-F]+)\"")
    return {m.group(1): int(m.group(2), 16) for m in rule.finditer(open(path).read())}


sets = {
    "material": {
        name: int(cp, 16) for name, cp in (line.split() for line in open(material_codepoints))
    },
    "phosphor": css_codepoints(css_sets[1], r"ph\.ph-"),
    "lucide": css_codepoints(css_sets[3], r"icon-"),
    "tabler": css_codepoints(css_sets[5], r"ti-"),
}
fonts = {
    "material": material_ttf,
    "phosphor": css_sets[0],
    "lucide": css_sets[2],
    "tabler": css_sets[4],
}
families = {
    "material": "Specimen Material Symbols",
    "phosphor": "Specimen Phosphor",
    "lucide": "Specimen Lucide",
    "tabler": "Specimen Tabler",
}

rows = [line.rstrip("\n").split("\t") for line in open(glyphs_path) if line.strip() and not line.startswith("#")]
order = ["material", "phosphor", "lucide", "tabler"]
table = []
for row in rows:
    ident, names = row[0], dict(zip(order, row[1:]))
    try:
        table.append([ident] + [f"{sets[s][names[s]]:x}" for s in order])
    except KeyError as missing:
        sys.exit(f"{ident}: no glyph {missing} in one of the sets")

with open(f"{out}/icons.tsv", "w") as tsv:
    tsv.write("# Generated by make-icons.sh from glyphs.tsv: each glyph's codepoint in each set.\n")
    tsv.write("# id\tmaterial\tphosphor\tlucide\ttabler\n")
    for row in table:
        tsv.write("\t".join(row) + "\n")

for i, s in enumerate(order):
    font = TTFont(fonts[s])
    if s == "material":
        # Kōbō's look: outlined, regular weight, the 24 px optical size.
        font = instancer.instantiateVariableFont(font, {"FILL": 0, "GRAD": 0, "opsz": 24, "wght": 400})
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 16, 17]
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[int(row[i + 1], 16) for row in table])
    subsetter.subset(font)
    family = families[s]
    plain = family.replace(" ", "")
    names = {1: family, 3: f"{plain}-Regular", 4: f"{family} Regular", 6: f"{plain}-Regular", 16: family, 17: "Regular"}
    for record in list(font["name"].names):
        if record.nameID in names:
            font["name"].setName(names[record.nameID], record.nameID, record.platformID, record.platEncID, record.langID)
    font.save(f"{out}/{s}.ttf")
    print(f"{out}/{s}.ttf: {family}, {len(table)} glyphs")
